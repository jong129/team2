CREATE TABLE DOC_RISK_FINDINGS (
    FINDING_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOC_ID         NUMBER NOT NULL,
    DOC_TYPE       VARCHAR2(50) NOT NULL,
    RULE_ID        NUMBER NOT NULL,
    RULE_TYPE      VARCHAR2(50) NOT NULL,
    DETAIL         VARCHAR2(500),
    CONFIDENCE     NUMBER(5,2),
    DETECTED_AT    DATE DEFAULT SYSDATE,
    FOREIGN KEY (DOC_ID) REFERENCES DOCUMENTS(DOC_ID)
);

COMMENT ON COLUMN DOC_RISK_FINDINGS.FINDING_ID  IS '검출된 위험 요소 고유 ID';
COMMENT ON COLUMN DOC_RISK_FINDINGS.DOC_ID      IS '문서 ID';
COMMENT ON COLUMN DOC_RISK_FINDINGS.DOC_TYPE    IS '문서 종류(CONTRACT/REGISTRY/BUILDING)';
COMMENT ON COLUMN DOC_RISK_FINDINGS.RULE_ID     IS '해당 위험 규칙의 ID';
COMMENT ON COLUMN DOC_RISK_FINDINGS.RULE_TYPE   IS '규칙 종류(CONTRACT/REGISTRY/BUILDING)';
COMMENT ON COLUMN DOC_RISK_FINDINGS.DETAIL      IS '검출된 위험 상세 설명';
COMMENT ON COLUMN DOC_RISK_FINDINGS.CONFIDENCE  IS 'AI가 해당 위험을 판단한 신뢰도 (0~1 또는 0~100)';
COMMENT ON COLUMN DOC_RISK_FINDINGS.DETECTED_AT IS '위험 요소 검출 시각';
