CREATE TABLE DOCUMENTS (
    DOC_ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID         NUMBER NOT NULL,
    DOC_TYPE        VARCHAR2(50) NOT NULL,
    FILE_PATH       VARCHAR2(500),
    STATUS          VARCHAR2(20) DEFAULT 'UPLOADED',
    CREATED_AT      DATE DEFAULT SYSDATE
);

COMMENT ON COLUMN DOCUMENTS.DOC_ID       IS '문서 고유 ID';
COMMENT ON COLUMN DOCUMENTS.USER_ID      IS '문서를 업로드한 사용자 ID';
COMMENT ON COLUMN DOCUMENTS.DOC_TYPE     IS '문서 종류(CONTRACT/REGISTRY/BUILDING)';
COMMENT ON COLUMN DOCUMENTS.FILE_PATH    IS '업로드된 실제 파일 경로';
COMMENT ON COLUMN DOCUMENTS.STATUS       IS '문서 분석 상태 (UPLOADED/ANALYZING/DONE)';
COMMENT ON COLUMN DOCUMENTS.CREATED_AT   IS '문서 업로드 일시';

CREATE TABLE DOCUMENT_CONTRACT (
    DOC_ID          NUMBER PRIMARY KEY,
    LESSOR_NAME     VARCHAR2(100),
    LESSEE_NAME     VARCHAR2(100),
    ADDRESS         VARCHAR2(300),
    DEPOSIT         NUMBER,
    MONTHLY_RENT    NUMBER,
    CONTRACT_DATE   DATE,
    EXPIRATION_DATE DATE,
    FOREIGN KEY (DOC_ID) REFERENCES DOCUMENTS(DOC_ID)
);

COMMENT ON COLUMN DOCUMENT_CONTRACT.DOC_ID          IS 'DOCUMENTS 테이블의 문서 ID';
COMMENT ON COLUMN DOCUMENT_CONTRACT.LESSOR_NAME     IS '임대인 이름';
COMMENT ON COLUMN DOCUMENT_CONTRACT.LESSEE_NAME     IS '임차인 이름';
COMMENT ON COLUMN DOCUMENT_CONTRACT.ADDRESS         IS '임대차 계약 대상 주소';
COMMENT ON COLUMN DOCUMENT_CONTRACT.DEPOSIT         IS '보증금 금액';
COMMENT ON COLUMN DOCUMENT_CONTRACT.MONTHLY_RENT    IS '월세 금액';
COMMENT ON COLUMN DOCUMENT_CONTRACT.CONTRACT_DATE   IS '계약 체결일';
COMMENT ON COLUMN DOCUMENT_CONTRACT.EXPIRATION_DATE IS '계약 종료 예정일';

CREATE TABLE DOCUMENT_REGISTRY (
    DOC_ID          NUMBER PRIMARY KEY,
    PROPERTY_ADDR   VARCHAR2(300),
    OWNER_NAME      VARCHAR2(100),
    MORTGAGE_COUNT  NUMBER,
    ATTACHMENTS     VARCHAR2(500),
    FOREIGN KEY (DOC_ID) REFERENCES DOCUMENTS(DOC_ID)
);

COMMENT ON COLUMN DOCUMENT_REGISTRY.DOC_ID          IS 'DOCUMENTS 테이블의 문서 ID';
COMMENT ON COLUMN DOCUMENT_REGISTRY.PROPERTY_ADDR   IS '부동산 소재지 주소';
COMMENT ON COLUMN DOCUMENT_REGISTRY.OWNER_NAME      IS '등기부 상 현재 소유자명';
COMMENT ON COLUMN DOCUMENT_REGISTRY.MORTGAGE_COUNT  IS '근저당 및 설정권 수';
COMMENT ON COLUMN DOCUMENT_REGISTRY.ATTACHMENTS     IS '기타 권리관계 (가압류, 가처분 등)';

CREATE TABLE DOCUMENT_BUILDING (
    DOC_ID              NUMBER PRIMARY KEY,
    PROPERTY_ADDR       VARCHAR2(300),
    BUILD_YEAR          NUMBER,
    STRUCTURE_TYPE      VARCHAR2(100),
    FLOOR_COUNT         NUMBER,
    AREA                NUMBER,
    FOREIGN KEY (DOC_ID) REFERENCES DOCUMENTS(DOC_ID)
);

COMMENT ON COLUMN DOCUMENT_BUILDING.DOC_ID         IS 'DOCUMENTS 테이블의 문서 ID';
COMMENT ON COLUMN DOCUMENT_BUILDING.PROPERTY_ADDR  IS '건축물 소재지';
COMMENT ON COLUMN DOCUMENT_BUILDING.BUILD_YEAR     IS '건축 연도';
COMMENT ON COLUMN DOCUMENT_BUILDING.STRUCTURE_TYPE IS '건축물 구조 타입(철근콘크리트, 목조 등)';
COMMENT ON COLUMN DOCUMENT_BUILDING.FLOOR_COUNT    IS '층수(지상/지하 포함)';
COMMENT ON COLUMN DOCUMENT_BUILDING.AREA           IS '연면적(㎡)';

CREATE TABLE DOCUMENT_ANALYSIS (
    ANALYSIS_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DOC_ID          NUMBER NOT NULL,
    SUMMARY         VARCHAR2(2000),
    RISK_SCORE      NUMBER(5,2),
    COMPLETED_AT    DATE DEFAULT SYSDATE,
    FOREIGN KEY (DOC_ID) REFERENCES DOCUMENTS(DOC_ID)
);

COMMENT ON COLUMN DOCUMENT_ANALYSIS.ANALYSIS_ID   IS '분석 결과 고유 ID';
COMMENT ON COLUMN DOCUMENT_ANALYSIS.DOC_ID        IS '대상 문서(DOCUMENTS) ID';
COMMENT ON COLUMN DOCUMENT_ANALYSIS.SUMMARY       IS 'AI가 생성한 분석 요약 내용';
COMMENT ON COLUMN DOCUMENT_ANALYSIS.RISK_SCORE    IS 'AI가 계산한 전체 위험 점수 (0~100)';
COMMENT ON COLUMN DOCUMENT_ANALYSIS.COMPLETED_AT  IS '분석이 완료된 일시';

CREATE TABLE CONTRACT_RISK_RULES (
