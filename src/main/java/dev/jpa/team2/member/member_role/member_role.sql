-- 회원 권한 전체 조회(관리자 페이지용)
SELECT 
    m.MEMBER_ID,
    m.LOGIN_ID,
    m.EMAIL,
    LISTAGG(r.ROLE_NAME, ', ') WITHIN GROUP (ORDER BY r.ROLE_NAME) AS ROLES
FROM MEMBER m
LEFT JOIN MEMBER_ROLE mr ON m.MEMBER_ID = mr.MEMBER_ID
LEFT JOIN ROLE r ON mr.ROLE_ID = r.ROLE_ID
GROUP BY m.MEMBER_ID, m.LOGIN_ID, m.EMAIL
ORDER BY m.MEMBER_ID;

