-- 특정 회원이 가진 전체 권한 보기
SELECT r.ROLE_NAME
FROM MEMBER_ROLE mr
JOIN ROLE r ON mr.ROLE_ID = r.ROLE_ID
WHERE mr.MEMBER_ID = 1;

-- 특정 권한을 가진 사용자 목록 조회
SELECT m.MEMBER_ID, m.LOGIN_ID, m.EMAIL, r.ROLE_NAME
FROM MEMBER_ROLE mr
JOIN MEMBER m ON mr.MEMBER_ID = m.MEMBER_ID
JOIN ROLE r ON mr.ROLE_ID = r.ROLE_ID
WHERE r.ROLE_NAME = 'ADMIN';

-- 권한 삭제
